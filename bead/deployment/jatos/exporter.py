"""JATOS exporter for jsPsych experiments.

This module provides the JATOSExporter class for creating JATOS study packages (.jzip)
from generated jsPsych experiments.
"""

from __future__ import annotations

import json
import re
import uuid
import zipfile
from pathlib import Path

from bead.data.base import BeadBaseModel, JsonValue


class JATOSExporter(BeadBaseModel):
    """Exports jsPsych experiments as JATOS study packages (.jzip).

    A .jzip file is a ZIP archive containing:
    - A .jas file containing the JATOS study metadata
    - The named assets directory containing all experiment files

    Attributes
    ----------
    study_title : str
        Title of the JATOS study.
    study_description : str
        Description of the study.
    study_uuid : UUID | None
        Stable study identity for reproducible exports and JATOS updates.

    Examples
    --------
    >>> from pathlib import Path
    >>> exporter = JATOSExporter("Test Study", "A test study")
    >>> # exporter.export(Path("experiment"), Path("study.jzip"))
    """

    study_title: str
    study_description: str = ""
    study_uuid: uuid.UUID | None = None

    def export(
        self,
        experiment_dir: Path,
        output_path: Path,
        component_title: str = "Main Experiment",
    ) -> None:
        """Create JATOS .jzip file.

        Parameters
        ----------
        experiment_dir : Path
            Directory containing experiment files (from JsPsychExperimentGenerator).
            Expected structure:
            - index.html
            - css/experiment.css
            - js/experiment.js
            - data/timeline.json
            - data/config.json
        output_path : Path
            Output path for .jzip file.
        component_title : str
            Title for the JATOS component.

        Raises
        ------
        ValueError
            If experiment_dir does not exist or is missing required files.
        FileNotFoundError
            If required experiment files are not found.

        Examples
        --------
        >>> exporter = JATOSExporter("Test Study")
        >>> exporter.export(Path("exp"), Path("study.jzip"))
        """
        if not experiment_dir.exists():
            raise ValueError(f"Experiment directory does not exist: {experiment_dir}")

        if not experiment_dir.is_dir():
            raise ValueError(f"Path is not a directory: {experiment_dir}")

        # verify required files exist
        required_files = ["index.html"]
        for file in required_files:
            if not (experiment_dir / file).exists():
                raise FileNotFoundError(
                    f"Required file not found: {experiment_dir / file}"
                )

        dir_name = self._sanitize_dirname(self.study_title)
        study_json = self._create_study_json(component_title)
        with zipfile.ZipFile(output_path, "w") as archive:
            self._write_entry(
                archive, f"{dir_name}.jas", json.dumps(study_json, indent=2).encode()
            )
            for path in sorted(experiment_dir.rglob("*")):
                if path.is_file() and path.resolve() != output_path.resolve():
                    relative = path.relative_to(experiment_dir).as_posix()
                    self._write_entry(
                        archive, f"{dir_name}/{relative}", path.read_bytes()
                    )

    @staticmethod
    def _write_entry(archive: zipfile.ZipFile, name: str, data: bytes) -> None:
        entry = zipfile.ZipInfo(name)
        entry.create_system = 3
        entry.external_attr = (0o100644 & 0xFFFF) << 16
        archive.writestr(entry, data, compress_type=zipfile.ZIP_DEFLATED)

    def _create_study_json(self, component_title: str) -> dict[str, JsonValue]:
        """Create the JATOS study descriptor.

        Parameters
        ----------
        component_title : str
            Title for the JATOS component.

        Returns
        -------
        dict[str, JsonValue]
            JATOS study metadata dictionary.

        Notes
        -----
        The .jas file follows JATOS v3 schema format.
        """
        study_uuid = self.study_uuid or uuid.uuid4()
        component_uuid = uuid.uuid5(study_uuid, "component")
        batch_uuid = uuid.uuid5(study_uuid, "batch")

        # sanitize title for directory name
        dir_name = self._sanitize_dirname(self.study_title)

        return {
            "version": "3",
            "data": {
                "uuid": str(study_uuid),
                "title": self.study_title,
                "description": self.study_description,
                "dirName": dir_name,
                "comments": "Generated by bead",
                "jsonData": None,
                "componentList": (
                    {
                        "uuid": str(component_uuid),
                        "title": component_title,
                        "htmlFilePath": "index.html",
                        "reloadable": False,
                        "active": True,
                        "comments": "",
                        "jsonData": None,
                    },
                ),
                "batchList": (
                    {
                        "uuid": str(batch_uuid),
                        "title": "Default",
                        "active": True,
                        "allowedWorkerTypes": (
                            "Jatos",
                            "PersonalSingle",
                            "PersonalMultiple",
                            "GeneralSingle",
                            "GeneralMultiple",
                        ),
                    },
                ),
                "groupStudy": False,
                "linearStudy": False,
                "allowPreview": True,
            },
        }

    def _sanitize_dirname(self, title: str) -> str:
        """Sanitize study title for use as directory name.

        Parameters
        ----------
        title : str
            Study title to sanitize.

        Returns
        -------
        str
            Sanitized directory name.

        Examples
        --------
        >>> exporter = JATOSExporter("My Study")
        >>> exporter._sanitize_dirname("My Study")
        'my_study'
        >>> exporter._sanitize_dirname("Study (2024)")
        'study_2024'
        """
        # convert to lowercase
        dirname = title.lower()

        # replace spaces with underscores
        dirname = dirname.replace(" ", "_")

        # remove non-alphanumeric characters (except underscores)
        dirname = re.sub(r"[^a-z0-9_]", "", dirname)

        # remove consecutive underscores
        dirname = re.sub(r"_+", "_", dirname)

        # remove leading/trailing underscores
        dirname = dirname.strip("_")

        # ensure it's not empty
        if not dirname:
            dirname = "study"

        return dirname
